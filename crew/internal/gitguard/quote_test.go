func TestQuoteMatchesBash(t *testing.T) {
	for _, tc := range quoteGolden {
		if got := Quote(tc.in); got != tc.want {
			t.Errorf("Quote(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}
